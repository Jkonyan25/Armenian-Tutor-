// Generates the bundled Eastern Armenian audio clips with eSpeak NG.
//
//   sudo apt-get install espeak-ng ffmpeg
//   node tools/build-audio.mjs          (only builds missing clips)
//   node tools/build-audio.mjs --force  (rebuilds everything)
//
// Writes audio/*.mp3 and js/audio-manifest.js.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import os from 'node:os';
import { execFileSync } from 'node:child_process';
import { ROOT, loadData, speechItems } from './load-data.mjs';

const force = process.argv.includes('--force');
const D = loadData();
const items = speechItems(D);
const outDir = path.join(ROOT, 'audio');
fs.mkdirSync(outDir, { recursive: true });
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'arm-audio-'));

const manifest = {};
let built = 0;
for (const [key, tts] of items) {
  const file = crypto.createHash('sha1').update(key).digest('hex').slice(0, 12) + '.mp3';
  manifest[key] = file;
  const out = path.join(outDir, file);
  if (!force && fs.existsSync(out)) continue;
  const wav = path.join(tmp, 'clip.wav');
  const isLong = tts.length > 40;
  // -v hy = Eastern Armenian (Yerevan). Slower speed for learners.
  execFileSync('espeak-ng', ['-v', 'hy', '-s', isLong ? '120' : '128', '-g', '4', '-w', wav, tts]);
  execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', wav,
    '-af', 'silenceremove=start_periods=1:start_threshold=-50dB,areverse,silenceremove=start_periods=1:start_threshold=-50dB,areverse,apad=pad_dur=0.12',
    '-ac', '1', '-ar', '22050', '-b:a', '48k', out]);
  built++;
}

// Remove clips that are no longer used.
const keep = new Set(Object.values(manifest));
for (const f of fs.readdirSync(outDir)) {
  if (f.endsWith('.mp3') && !keep.has(f)) fs.unlinkSync(path.join(outDir, f));
}

const sorted = Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync(path.join(ROOT, 'js/audio-manifest.js'),
  '/* Generated by tools/build-audio.mjs. Do not edit by hand. */\n' +
  'window.AUDIO_MANIFEST = ' + JSON.stringify(sorted, null, 0).replace(/","/g, '",\n"') + ';\n');
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`Audio: ${items.size} clips (${built} newly built).`);
